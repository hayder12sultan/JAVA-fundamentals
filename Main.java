
public class Main {
    public static void main(String[] args) {

        // 1. Integer variable
        int age = 20;
        System.out.println(age); // 20

        // 2. Decimal variable
        double price = 25.5;
        System.out.println(price); // 25.5

        // 3. Text variable
        String name = "Abel";
        System.out.println(name); // Abel

        // 4. Single character
        char grade = 'A';
        System.out.println(grade); // A

        // 5. Boolean variable
        boolean isStudent = true;
        System.out.println(isStudent); // true

        // 6. Change a variable's value
        int score = 80;
        score = 95;
        System.out.println(score); // 95

        // 7. Declare first, assign later
        int number;
        number = 100;
        System.out.println(number); // 100

        // 8. Multiple variables
        int x = 10, y = 20;
        System.out.println(x + y); // 30

        // 9. Constants (cannot be reassigned)
        final double PI = 3.14159;
        System.out.println(PI); // 3.14159

        // 10. Variable calculation
        int a = 5;
        int b = 3;
        int sum = a + b;
        System.out.println(sum); // 8
    }
}
